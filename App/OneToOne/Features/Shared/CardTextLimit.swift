import SwiftUI

extension View {
    /// Карточки на «Главной» (подсказка у него, «Сегодня» у неё, дни рождения и годовщина) растут
    /// со шрифтом только до `.accessibility2`: крупнее «Фолликулярная», «Комплимент» и «годовщиной!»
    /// не влезают в ширину карточки на iPhone SE и рвутся посреди слова.
    /// Предел на всю карточку, чтобы заголовок не стал крупнее текста под ним.
    func cardTextLimit() -> some View {
        dynamicTypeSize(...DynamicTypeSize.accessibility2)
    }
}
